"""Generate the bundled tool list and the Rust, TypeScript and Python bindings from schemas/.

    python3 tools/schema/codegen.py          # write
    python3 tools/schema/codegen.py --check  # fail if any generated file is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import schemalib as sl  # noqa: E402

HEADER = "@generated by tools/schema/codegen.py from schemas/. Do not edit."
OUT_BUNDLE = sl.REPO / "schemas/dist/tools.bundle.json"
OUT_RUST = sl.REPO / "infra/crates/proto/src/generated.rs"
OUT_TS = sl.REPO / "harness/tools/src/generated/infra-tools.ts"
OUT_PY = sl.REPO / "tests/lib/agentinfra_tools.py"


def camel(s: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", s)
    return "".join(p[:1].upper() + p[1:].lower() for p in parts if p)


def string_enums(defs: dict) -> dict[str, list[str]]:
    return {k: v["enum"] for k, v in defs.items() if "enum" in v and all(isinstance(x, str) for x in v["enum"])}


# ---------------------------------------------------------------- Rust (std only)
def rust(bundle: dict, defs: dict) -> str:
    out = [f"// {HEADER}", "#![allow(clippy::all)]", ""]
    errors = bundle["errors"]
    out.append("/// Every Infra tool error code (schemas/common/errors.json).")
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
    out.append("pub enum ErrorCode {")
    out += [f"    {camel(e['code'])}," for e in errors]
    out.append("}")
    out.append("")
    out.append("impl ErrorCode {")
    out.append("    pub const ALL: &'static [ErrorCode] = &[" + ", ".join(f"ErrorCode::{camel(e['code'])}" for e in errors) + "];")
    out.append("    pub const fn as_str(self) -> &'static str {")
    out.append("        match self {")
    out += [f"            ErrorCode::{camel(e['code'])} => \"{e['code']}\"," for e in errors]
    out.append("        }")
    out.append("    }")
    out.append("    /// Whether the caller may retry the same call (with the same idempotency key).")
    out.append("    pub const fn retryable(self) -> bool {")
    out.append("        match self {")
    out += [f"            ErrorCode::{camel(e['code'])} => {str(e['retryable']).lower()}," for e in errors]
    out.append("        }")
    out.append("    }")
    out.append("    pub fn parse(s: &str) -> Option<ErrorCode> {")
    out.append("        Self::ALL.iter().copied().find(|c| c.as_str() == s)")
    out.append("    }")
    out.append("}")
    out.append("")
    for name, values in string_enums(defs).items():
        if name == "ErrorCode":
            continue
        out.append(f"#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
        out.append(f"pub enum {name} {{")
        out += [f"    {camel(v)}," for v in values]
        out.append("}")
        out.append("")
        out.append(f"impl {name} {{")
        out.append(f"    pub const ALL: &'static [{name}] = &[" + ", ".join(f"{name}::{camel(v)}" for v in values) + "];")
        out.append("    pub const fn as_str(self) -> &'static str {")
        out.append("        match self {")
        out += [f"            {name}::{camel(v)} => \"{v}\"," for v in values]
        out.append("        }")
        out.append("    }")
        out.append(f"    pub fn parse(s: &str) -> Option<{name}> {{")
        out.append("        Self::ALL.iter().copied().find(|v| v.as_str() == s)")
        out.append("    }")
        out.append("}")
        out.append("")
    out.append("/// One MCP tool as published by infrad. Schemas are self-contained JSON.")
    out.append("#[derive(Debug, Clone, Copy)]")
    out.append("pub struct ToolDef {")
    out.append("    pub name: &'static str,")
    out.append("    pub group: &'static str,")
    out.append("    pub description: &'static str,")
    out.append("    pub mutates: bool,")
    out.append("    pub long_running: bool,")
    out.append("    pub roles: &'static [Role],")
    out.append("    pub harness_builtin: &'static [&'static str],")
    out.append("    pub input_schema: &'static str,")
    out.append("    pub output_schema: &'static str,")
    out.append("}")
    out.append("")
    out.append("pub mod names {")
    for t in bundle["tools"]:
        out.append(f"    pub const {t['name'].upper()}: &str = \"{t['name']}\";")
    out.append("}")
    out.append("")
    out.append("pub static TOOLS: &[ToolDef] = &[")
    for t in bundle["tools"]:
        roles = ", ".join(f"Role::{camel(r)}" for r in t["roles"])
        builtin = ", ".join(f'"{b}"' for b in t.get("harness_builtin", []))
        out.append("    ToolDef {")
        out.append(f"        name: \"{t['name']}\",")
        out.append(f"        group: \"{t['group']}\",")
        out.append(f"        description: {json.dumps(t['description'], ensure_ascii=False)},")
        out.append(f"        mutates: {str(t['mutates']).lower()},")
        out.append(f"        long_running: {str(t.get('long_running', False)).lower()},")
        out.append(f"        roles: &[{roles}],")
        out.append(f"        harness_builtin: &[{builtin}],")
        out.append(f"        input_schema: r##\"{json.dumps(t['inputSchema'], ensure_ascii=False, separators=(',', ':'))}\"##,")
        out.append(f"        output_schema: r##\"{json.dumps(t['outputSchema'], ensure_ascii=False, separators=(',', ':'))}\"##,")
        out.append("    },")
    out.append("];")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- TypeScript
def ts_type(s: dict, ind: str = "") -> str:
    if "$ref" in s:
        return sl.ref_name(s["$ref"])
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(ts_type(x, ind) for x in s[key])
    t = s.get("type")
    if t == "object":
        props = s.get("properties")
        if not props:
            return "Record<string, unknown>"
        req = set(s.get("required", []))
        inner = ind + "  "
        lines = ["{"]
        for k, v in props.items():
            if "description" in v:
                lines.append(f"{inner}/** {v['description']} */")
            lines.append(f"{inner}{k}{'' if k in req else '?'}: {ts_type(v, inner)};")
        if s.get("additionalProperties") is True:
            lines.append(f"{inner}[key: string]: unknown;")
        lines.append(ind + "}")
        return "\n".join(lines)
    if t == "array":
        item = ts_type(s["items"], ind)
        return f"Array<{item}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}[t]


def ts(bundle: dict, defs: dict, tools: list[sl.Tool]) -> str:
    out = [f"// {HEADER}", ""]
    for name, d in defs.items():
        body = ts_type(d)
        if d.get("type") == "object" and d.get("properties"):
            out.append(f"export interface {name} {body}")
        else:
            out.append(f"export type {name} = {body};")
        out.append("")
    out.append("export const RETRYABLE: Readonly<Record<ErrorCode, boolean>> = {")
    out += [f"  {e['code']}: {str(e['retryable']).lower()}," for e in bundle["errors"]]
    out.append("};")
    out.append("")
    for t in tools:
        base = camel(t.name)
        out.append(f"export interface {base}Input {ts_type(t.doc['inputSchema'])}")
        out.append("")
        oschema = t.doc["outputSchema"]
        if "$ref" in oschema:
            out.append(f"export type {base}Output = {ts_type(oschema)};")
        else:
            out.append(f"export interface {base}Output {ts_type(oschema)}")
        out.append("")
    out.append("export interface InfraTools {")
    for t in tools:
        base = camel(t.name)
        out.append(f"  {t.name}: {{ input: {base}Input; output: {base}Output }};")
    out.append("}")
    out.append("")
    out.append("export type InfraToolName = keyof InfraTools;")
    out.append("")
    out.append("export interface ToolMeta {")
    out.append("  group: string;")
    out.append("  mutates: boolean;")
    out.append("  longRunning: boolean;")
    out.append("  roles: readonly Role[];")
    out.append("  harnessBuiltin: readonly (\"read\" | \"write\" | \"edit\" | \"bash\")[];")
    out.append("}")
    out.append("")
    out.append("export const TOOL_META: Readonly<Record<InfraToolName, ToolMeta>> = {")
    for t in bundle["tools"]:
        roles = ", ".join(json.dumps(r) for r in t["roles"])
        builtin = ", ".join(json.dumps(b) for b in t.get("harness_builtin", []))
        out.append(f"  {t['name']}: {{ group: {json.dumps(t['group'])}, mutates: {str(t['mutates']).lower()}, "
                   f"longRunning: {str(t.get('long_running', False)).lower()}, roles: [{roles}], harnessBuiltin: [{builtin}] }},")
    out.append("};")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- Python
def py_type(s: dict) -> str:
    if "$ref" in s:
        return sl.ref_name(s["$ref"])
    if "const" in s:
        return f"Literal[{s['const']!r}]"
    if "enum" in s:
        return "Literal[" + ", ".join(repr(v) for v in s["enum"]) + "]"
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(py_type(x) if x.get("type") != "null" else "None" for x in s[key])
    t = s.get("type")
    if t == "object":
        return "dict[str, Any]"
    if t == "array":
        return f"list[{py_type(s['items'])}]"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}[t]


def py_typeddict(name: str, s: dict) -> list[str]:
    """Functional form, because field names such as `from` are Python keywords."""
    req = set(s.get("required", []))
    lines = [f"{name} = TypedDict(", f"    {name!r},", "    {"]
    for k, v in s.get("properties", {}).items():
        t = py_type(v)
        t = f"Required[{t!r}]" if k in req else repr(t)  # string forward references
        lines.append(f"        {k!r}: {t},")
    lines += ["    },", "    total=False,", ")"]
    return lines


def py(bundle: dict, defs: dict, tools: list[sl.Tool]) -> str:
    out = [f"# {HEADER}", "from __future__ import annotations", "", "from typing import Any, Literal, Required, TypedDict", ""]
    for name, d in defs.items():
        if d.get("type") == "object" and d.get("properties"):
            out += py_typeddict(name, d)
        else:
            out.append(f"{name} = {py_type(d)}")
        out.append("")
    out.append("RETRYABLE: dict[str, bool] = {")
    out += [f"    {e['code']!r}: {e['retryable']}," for e in bundle["errors"]]
    out.append("}")
    out.append("")
    for t in tools:
        base = camel(t.name)
        out += py_typeddict(f"{base}Input", t.doc["inputSchema"])
        out.append("")
    out.append("MUTATING_TOOLS: frozenset[str] = frozenset({")
    out += [f"    {t['name']!r}," for t in bundle["tools"] if t["mutates"]]
    out.append("})")
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    defs = sl.load_defs()
    tools = sl.load_tools()
    bundle = sl.bundle_all()
    files = {
        OUT_BUNDLE: sl.dumps(bundle),
        OUT_RUST: rust(bundle, defs),
        OUT_TS: ts(bundle, defs, tools),
        OUT_PY: py(bundle, defs, tools),
    }
    stale = []
    for path, text in files.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(sl.REPO))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated files (run: just codegen):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    print("codegen " + ("up to date" if check else "written") + f": {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
